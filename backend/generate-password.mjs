import { randomBytes, pbkdf2Sync, createHmac } from 'node:crypto';
const password=randomBytes(24).toString('base64url');
const pepper=randomBytes(48).toString('base64url');
const salt=randomBytes(24);
const keyed=createHmac('sha256',pepper).update(password).digest();
console.log('NEW ADMIN PASSWORD (keep private): '+password);
console.log('ADMIN_PASSWORD_SALT='+salt.toString('base64url'));
console.log('ADMIN_PASSWORD_HASH='+pbkdf2Sync(keyed,salt,100000,32,'sha256').toString('base64url'));
console.log('PASSWORD_PEPPER='+pepper);
console.log('SESSION_SECRET='+randomBytes(48).toString('base64url'));
